const ACCOUNT_TYPES = { 2: "Checking", 3: "Savings", 4: "General ledger", 5: "Loan" };
const KIND_BY_DIGIT = {
  1: "return",
  6: "return",
  3: "prenote",
  8: "prenote",
  4: "zero",
  9: "zero",
};
const KIND_LABELS = { return: "return/NOC ", prenote: "prenote ", zero: "zero-dollar ", live: "" };

export function describeTransactionCode(code) {
  const text = String(code);
  const account = ACCOUNT_TYPES[text[0]];
  if (!VALID_TRANSACTION_CODES.has(Number.parseInt(text, 10)) || !account) {
    return {
      label: `Unknown code ${text}`,
      account: null,
      debit: false,
      kind: "unknown",
      valid: false,
    };
  }
  const digit = Number(text[1]);
  const debit = digit >= 5;
  const kind = KIND_BY_DIGIT[digit] ?? "live";
  return {
    label: `${account} ${KIND_LABELS[kind]}${debit ? "debit" : "credit"}`,
    account,
    debit,
    kind,
    valid: true,
  };
}
